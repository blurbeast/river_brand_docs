#!/usr/bin/env python3
"""Generate front-matter/f07-list-of-figures.md from live figure markers and Mermaid captions."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

FIG_RE = re.compile(r"<!--\s*FIGURE:\s*(\S+)\s*\|\s*([^>]+?)\s*-->")
CAP_RE = re.compile(r"^\*\*Figure\s+([\d.]+)\s*[—-]\s*(.+?)\.\*\*\s*$")

entries = []  # (chapter_label, figure_id, caption, kind)

for sub in ("chapters", "appendices", "front-matter"):
    d = ROOT / sub
    if not d.exists():
        continue
    for p in sorted(d.glob("*.md")):
        label = p.stem
        m = re.match(r"ch(\d+)", p.stem)
        if m:
            label = f"Ch. {int(m.group(1))}"
        elif p.stem.startswith("app-"):
            label = "App. " + p.stem.split("-")[1].upper()
        text = p.read_text()
        for fm in FIG_RE.finditer(text):
            entries.append((label, fm.group(1), fm.group(2), "SVG"))
        for im in re.finditer(r"!\[([^\]]+)\]\(\.\./images/([^\)]+)\)", text):
            cap, fname = im.group(1), im.group(2)
            kind = "Mermaid" if "-mermaid-" in fname else "SVG"
            entries.append((label, fname, cap if cap.startswith("Figure") else f"{cap}", kind))
        # Mermaid captions: bold line immediately above ```mermaid
        lines = text.splitlines()
        for i, line in enumerate(lines):
            cm = CAP_RE.match(line.strip())
            if cm and i + 1 < len(lines) and lines[i + 1].strip().startswith("```mermaid"):
                entries.append((label, f"fig-{p.stem}-mermaid-{cm.group(1)}", f"Figure {cm.group(1)} — {cm.group(2)}", "Mermaid"))

# de-dupe by caption text
seen = set()
out = ["# List of Figures", ""]
out.append("Every diagram in this book is listed here. *Mermaid* figures render live in the web edition; *SVG* figures are hand-drawn textbook illustrations.")
out.append("")
out.append("| Figure | Title | Kind | Appears in |")
out.append("|---|---|---|---|")
for label, fid, cap, kind in entries:
    key = (cap, label)
    if key in seen:
        continue
    seen.add(key)
    cap_clean = cap.replace("|", "/")
    out.append(f"| {fid} | {cap_clean} | {kind} | {label} |")
out.append("")
out.append("*Generated by `scripts/gen_lof.py` — regenerate whenever figures change (`make lof`).*")

(ROOT / "front-matter" / "f07-list-of-figures.md").write_text("\n".join(out) + "\n")
print(f"wrote f07-list-of-figures.md with {len(seen)} figures")
